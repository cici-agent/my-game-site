function buildItems(slot, designs) {
  return Object.freeze(Object.entries(designs).flatMap(([hero, entries]) =>
    entries.map(([title, color, description], index) => {
      const tier = index + 1;
      const grade = grades[index];
      return Object.freeze({
        id: `${hero}.${slot}.${String(tier).padStart(2, '0')}`,
        hero, tier, name: `${grade}·${title}`, grade, color, description
      });
    })
  ));
}

